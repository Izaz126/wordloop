def extract_pdf2(pdf_path='vocabulary-pdfs/main.pdf'):
    reader = pypdf.PdfReader(pdf_path)
    total_pages = len(reader.pages)
    
    full_text = ''
    for p in reader.pages:
        full_text += (p.extract_text() or '') + '\n'
        
    lines = full_text.splitlines()
    entries = []
    excluded_lines = 0
    
    for l in lines:
        line_clean = l.strip()
        if not line_clean:
            continue
            
        # Detect headers/footers to exclude
        if any(h in line_clean for h in ['https://t.me', 'FB:-NUR UDDIN', '1000VOCABULARY', 'AUGUST', 'SEPTEMBER', 'OCTOBER', 'Page ']):
            excluded_lines += 1
            continue
            
        m = re.match(r'^\s*(\d{1,4})\s*[:.]\s*([A-Za-z\s\-\'/()’\']+?)\s*[-–—:]\s*(.+)', line_clean)
        if m:
            num = int(m.group(1))
            raw_word = m.group(2).strip()
            raw_meaning = m.group(3).strip()
            
            cleaned_meaning = clean_bangla(raw_meaning)
            slash_words = [w.strip() for w in raw_word.split('/') if w.strip()]
            
            for sw in slash_words:
                clean_w = re.sub(r'[^A-Za-z\s\-\']', '', sw).strip()
                if clean_w and len(clean_w) >= 2:
                    entries.append({
                        'num': num,
                        'word': clean_w,
                        'banglaMeaning': cleaned_meaning,
                        'source': f'BCS & Job Exams (main.pdf #{num})'
                    })
        else:
            if any(c.isalpha() for c in line_clean):
                excluded_lines += 1
                
    return total_pages, entries, excluded_lines

